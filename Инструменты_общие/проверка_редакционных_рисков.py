# Общая проверка редакционных рисков новых рассказов, 24.11.2026.
# Приближённая проверка, не официальный фильтр Дзена.
import re


_HARD = re.compile(
    r'\b(?:смерт[а-яё]*|умер(?:еть|ла|ло|ли|ш[а-яё]+)?|умира[а-яё]*|'
    r'погиб[а-яё]*|гибел[а-яё]*|покойн[а-яё]*|м[её]ртв[а-яё]*|'
    r'похорон[а-яё]*|могил[а-яё]*|кладбищ[а-яё]*|гроб(?:а|у|ом|е|ы|ов|ам|ами|ах)?|'
    r'помин(?:ки|ок|кам|ками|ках|альн[а-яё]+)|усопш[а-яё]*|труп[а-яё]*|'
    r'сконч(?:ался|алась|алось|ались|аться|ан[а-яё]+)|самоубий[а-яё]*|'
    r'бездыхан[а-яё]*|погребени[а-яё]*|'
    # с 25.11.2026: просторечные и обрядовые формы
    r'помер(?:ла|ло|ли)?|помира[а-яё]*|помр[её][а-яё]*|(?:с|по)?хорон(?:ил|ила|или|ить|ят|ит|ишь|им|ю|ен[а-яё]*)|'
    r'преставил[а-яё]*|отпевани[а-яё]*|отпел[а-яё]*|панихид[а-яё]*|погост(?:а|е|ом|у)?|надгроб[а-яё]*|'
    r'сороковин[а-яё]*|девятин[а-яё]*)\b', re.I)
# Брань и оскорбления в любой речи, включая реплики (с 25.11.2026, разбор Дзен.Гуру: язык вражды и токсичность)
_INSULT = re.compile(
    r'\b(?:дур(?:а|ы|е|у|ой|ою|ак|ака|аку|аком|аке|аки|аков|акам|аками|ень|ня|ищ[а-яё]*)|'
    r'идиот[а-яё]*|дебил[а-яё]*|кретин[а-яё]*|придур[а-яё]*|недоум[а-яё]*|сволоч[а-яё]*|стерв[а-яё]*|'
    r'гадин[а-яё]*|мраз[ьи]|паскуд[а-яё]*|шлюх[а-яё]*|потаскух[а-яё]*|шалав[а-яё]*|курв[а-яё]*|падл[а-яё]*|'
    r'урод(?:ина|ины|ине|ину|иной|а|у|ом|ы|ов)?|ублюд[а-яё]*|выродо?к[а-яё]*|убог(?:ая|ий|ой|ую|ие|их|ими|ого|ому)|'
    r'деревенщин[а-яё]*|лимит(?:а|е|у|ой)|хабалк[а-яё]*|быдл[а-яё]*|нагуляш[а-яё]*|байстрюк[а-яё]*|'
    r'голодран(?:ка|ки|ке|ку|кой|ец|ца|цу|цем|цы|цев)|нищеброд[а-яё]*|дармоед[а-яё]*|сопляк[а-яё]*|соплячк[а-яё]*|бестолоч[ьи])\b', re.I)
# по контексту: бывает и не бранью (скотина в хлеву, сук дерева, чурки на дрова, подстилка под скот, приживалка как положение)
_INSULT_CTX = re.compile(r'\b(?:скотин[а-яё]*|сук(?:а|и|е|у|ой)|сучк[а-яё]*|твар(?:ь|и|ью)|гад(?:ы|ов)?|дур[её]х[а-яё]*|дурочк[а-яё]*|чурк[а-яё]*|приживалк[а-яё]*|подстилк[а-яё]*|змея|змеюк[а-яё]*|ведьм[а-яё]*)\b', re.I)
# Эвфемизмы смерти (с 26.11.2026: проверка Дзен.Гуру отметила «её не стало» в «Своих», 136, как брак)
_EUPH = re.compile(
    r'\b(?:не стало|ушл[аи]? из жизни|ушёл из жизни|уход[а-яё]* из жизни|в мир иной|на тот свет|на том свете|упокои[а-яё]*|'
    r'почил[аи]?|в последний путь|царстви[еяю] небесн[а-яё]*|царство небесное|вечная память|светл[а-яё]+ памят[а-яё]*|'
    r'земля (?:ему |ей )?пухом|приказал[аи]? долго жить|ушл[аи]? на покой|ушёл на покой|отмучил[а-яё]*)\b', re.I)
# Ритм и чувства (с 26.11.2026, «Барская воля» 58 «ИИшная белиберда»): мягкие проверки, пороги по 562 рассказам
_FEEL = re.compile(r'(?<![а-яё])(?:жалк[оа]|жаль|страшн[а-яё]*|страх[а-яё]*|боял[а-яё]*|боюсь|боится|испуг[а-яё]*|обид[а-яё]*|стыд[а-яё]*|совестн[а-яё]*|'
    r'рад(?:а|ой|ость[а-яё]*|остн[а-яё]*)|сл[её]з[а-яё]*|плак[а-яё]*|злост[а-яё]*|злил[а-яё]*|зло(?![а-яё])|ненавид[а-яё]*|тоск[а-яё]*|горьк[а-яё]*|больно|'
    r'тревог[а-яё]*|тревож[а-яё]*|сердит[а-яё]*|сердил[а-яё]*|гнев[а-яё]*|досад[а-яё]*|отчаян[а-яё]*|надежд[а-яё]*|надеял[а-яё]*|счаст[а-яё]*|ревн[а-яё]*|завид[а-яё]*|'
    r'ох|ой|ишь|господи|батюшки|матушки)(?![а-яё])')
_WIDOW = re.compile(r'\b(?:вдов[а-яё]*|овдов[а-яё]*)\b', re.I)
_CONTEXT = re.compile(r'\b(?:кров(?:ь|и|ью|ав[а-яё]+|оточ[а-яё]+)|перелом[а-яё]*|сирот[а-яё]*)\b', re.I)
_STAMP = re.compile(r'\b(?:секунд[а-яё]*|минут[а-яё]*)\s+(?:словно\s+)?тяну[а-яё]*\s+(?:как|словно|будто)\s+час[а-яё]*\b', re.I)
_NUM = re.compile(
    r'^(?:один|одна|одно|одни|одного|одному|одним|одной|одну|одних|одними|'
    r'два|две|двух|двум|двумя|три|трех|трем|тремя|четыре|четырех|четырем|четырьмя|'
    r'нол[ьяюе]|нул[ьяюе]|пять|пяти|пятью|шесть|шести|шестью|семь|семи|семью|'
    r'восемь|восьми|восемью|восьмью|девять|девяти|девятью|десять|десяти|десятью|'
    r'(?:один|две|три|четыр|пят|шест|сем|восем|девят)надцат(?:ь|и|ью|ый|ая|ое|ые|ого|ой|ому|ым|ом|ых|ыми|ую)|'
    r'(?:двадцат|тридцат)(?:ь|и|ью|ый|ая|ое|ые|ого|ой|ому|ым|ом|ых|ыми|ую)|сорок|сорока|'
    r'пятьдесят|пятидесяти|шестьдесят|шестидесяти|семьдесят|семидесяти|восемьдесят|восьмидесяти|девяносто|девяноста|'
    r'сто|ста|двести|двухсот|триста|трехсот|четыреста|четырехсот|'
    r'пятьсот|пятисот|шестьсот|шестисот|семьсот|семисот|восемьсот|восьмисот|девятьсот|девятисот|'
    r'тысяч(?:а|и|у|е|ей|ам|ами|ах)?|миллион(?:а|у|ом|е|ы|ов|ам|ами|ах)?|миллиард(?:а|у|ом|е|ы|ов|ам|ами|ах)?|'
    r'двое|двоих|двоим|двоими|трое|троих|троим|троими|четверо|четверых|четверым|четверыми|'
    r'пятеро|пятерых|шестеро|шестерых|семеро|семерых|оба|обе|обоих|обеих|полтора|полторы|полутора|'
    r'(?:перв|втор|трет|четверт|пят|шест|седьм|восьм|девят|десят|сороков|'
    r'пятидесят|шестидесят|семидесят|восьмидесят|девяност|сот|двухсот|трехсот|четырехсот|тысячн)'
    r'(?:ый|ой|ий|ая|ья|ое|ье|ые|ьи|ого|ьего|ей|ому|ьему|ым|им|ом|ьем|ых|ьих|ыми|ьими|ую|ью))$')
_TOKEN = re.compile(r'\d{1,2}[./-]\d{1,2}[./-]\d{2,4}(?!\d)|\d{4}-\d{2}-\d{2}(?!\d)|\d{1,2}:\d{2}(?!\d)|\d+(?:[.,]\d+)?|[а-яё]+|[^\s]', re.I)

def number_expressions(value):
    """Приближённый счёт: соседние числительные образуют одно выражение."""
    result = []
    start = end = None
    for token in _TOKEN.finditer(value.lower().replace('ё', 'е')):
        word = token.group()
        if word[0].isdigit() or _NUM.fullmatch(word):
            if start is None:
                start = token.start()
            end = token.end()
        elif start is not None:
            result.append(value[start:end])
            start = end = None
    if start is not None:
        result.append(value[start:end])
    return result

# (верхняя граница объёма, нижняя/верхняя идеала, нижняя/верхняя порога).
# Порог свыше 9000 не масштабируется: источник от 25.11.2026.
_NUMBER_BANDS = (
    (3000, 8, 12, 20, 25),
    (5000, 12, 18, 35, 40),
    (7000, 15, 22, 45, 50),
    (9000, 20, 28, 55, 60),
    (float('inf'), 25, 35, 65, 75),
)

def number_limits(length):
    """Возвращает идеальный диапазон и диапазон допустимого порога."""
    for upper, ideal_lo, ideal_hi, limit_lo, limit_hi in _NUMBER_BANDS:
        if length <= upper:
            return ideal_lo, ideal_hi, limit_lo, limit_hi

def _locations(pattern, value, label):
    for i, line in enumerate(value.splitlines(), 1):
        found = pattern.findall(line)
        if found:
            print(f'  {label}, абзац {i}: {", ".join(found)} | {line[:150]}')

def apply(check, title, body):
    """Использует check штатного скрипта; возвращает ручные предупреждения."""
    manual = []
    hits = _HARD.findall(title) + _WIDOW.findall(title)
    check(not hits, 'Лексика утраты в заголовке', ', '.join(hits) or 'нет', '0')
    hard = _HARD.findall(body)
    check(not hard, 'Прямая траурная лексика', len(hard), '0; факт передать нейтрально')
    if hard:
        _locations(_HARD, body, 'ИСПРАВИТЬ')
    euph = _EUPH.findall(body) + _EUPH.findall(title)
    check(not euph, 'Эвфемизмы смерти', len(euph), '0: «не стало», «ушла из жизни», «в мир иной» тоже брак Дзен.Гуру; факт не называть или «осталась одна», «осталась без него»; «не стало» не о человеке перестроить')
    if euph:
        _locations(_EUPH, body, 'ИСПРАВИТЬ эвфемизм')
    insult = _INSULT.findall(body) + _INSULT.findall(title)
    check(not insult, 'Брань и оскорбления', len(insult), '0 и в репликах: «бестолковая», «бессовестная», «оглашенная» или поступок вместо слова')
    if insult:
        _locations(_INSULT, body, 'ИСПРАВИТЬ брань')
    if _INSULT_CTX.search(body):
        _locations(_INSULT_CTX, body, 'ПРОВЕРИТЬ, не брань ли')
        manual.append('слова, которые бывают бранью (скотина, тварь, дурёха, ведьма и др.)')
    widow = _WIDOW.findall(body)
    check(len(widow) <= 1, 'Лексика вдовства', len(widow), '0 или 1 при сюжетной необходимости')
    if widow:
        _locations(_WIDOW, body, 'ПРОВЕРИТЬ необходимость')
        if len(widow) == 1:
            manual.append('необходимость упоминания вдовства')
    if _CONTEXT.search(body):
        _locations(_CONTEXT, body, 'ПРОВЕРИТЬ контекст')
        manual.append('контекст чувствительной лексики')
    stamp = _STAMP.findall(body)
    check(not stamp, 'Штамп ожидания', len(stamp), '0')
    if stamp:
        _locations(_STAMP, body, 'ИСПРАВИТЬ штамп')
    _ru = [l for l in body.splitlines() if l.strip() and not re.search(r'[A-Za-z]{4}', l)]
    _auth = ' '.join(l for l in _ru if not l.lstrip().startswith('—'))
    _sl = [len(s.split()) for s in re.split(r'(?<=[.!?…])\s+', _auth) if s.split()]
    if len(_sl) > 20:
        _m = sum(_sl) / len(_sl)
        _cv = (sum((x - _m) ** 2 for x in _sl) / len(_sl)) ** 0.5 / _m
        if _cv < 0.42:
            print(f'ПРОВЕРИТЬ Разброс длины предложений: {_cv:.2f} (норма от 0,42; ниже звучит как протокол: короткие и длинные вперемешку, два подряд не с имени героини)')
            manual.append('ритм: однообразные предложения')
        else:
            print(f'OK        Разброс длины предложений: {_cv:.2f} (норма от 0,42)')
    _w = len(' '.join(_ru).split()) or 1
    _f = len(_FEEL.findall(' '.join(_ru).lower()))
    if _f < 3 or _f / _w * 1000 < 1.2:
        print(f'ПРОВЕРИТЬ Слова чувства: {_f} ({_f / _w * 1000:.1f} на 1000 слов; норма от 3 и от 1,2: в 3–5 местах сказать простыми словами, что героиня чувствует или думает, СТИЛЬ.md)')
        manual.append('чувства героини простыми словами')
    else:
        print(f'OK        Слова чувства: {_f} ({_f / _w * 1000:.1f} на 1000 слов, норма от 1,2)')
    count = sum(len(number_expressions(p)) for p in body.splitlines())
    length = len(body.replace('\n', ' '))
    ideal_lo, ideal_hi, limit_lo, limit = number_limits(length)
    norm = f'идеал {ideal_lo}–{ideal_hi}; порог {limit_lo}–{limit}; {length} знаков'
    check(count <= limit, 'Числовая нагрузка', count, norm)
    if count > ideal_hi:
        print(f'ПРОВЕРИТЬ Числовая нагрузка: {count}, выше идеального максимума {ideal_hi}; убрать лишние числа')
        manual.append('лишние числа: убрать или обосновать; сверх порога согласовать с владельцем')
        for i, p in enumerate(body.splitlines(), 1):
            nums = number_expressions(p)
            if nums:
                print(f'  абзац {i}: {", ".join(nums)} | {p[:150]}')
    return manual

if __name__ == '__main__':
    assert _HARD.search('покойницкой') and _HARD.search('умерла')
    assert _HARD.search('смертельную') and _HARD.search('похорон')
