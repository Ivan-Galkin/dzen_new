# Проверка чисел в рассказе (с 06.11.2026, Логика_повествования.md, Л20).
# Повод: «Повариха с перевала» (Свои, 89): «Три пальца не спасла, а восемь спасла», а в начале у героя повреждены два пальца.
# Скрипт сам вызывается из проверка_рассказа.py; можно и отдельно: python3 проверка_чисел.py Рассказ-NN_ГОТОВО-К-ВСТАВКЕ.md
# Что делает:
#   ИСПРАВИТЬ: пальцев больше десяти (одним числом или частями в одной фразе: «три не спасла, а восемь спасла»).
#   ПРОВЕРИТЬ: «три руки», «четыре ноги» (у табурета можно).
#   ПРОВЕРИТЬ: фразы с двумя и больше числами (части и целое сходятся?) и одно слово с разными числами в разных местах.
import re, sys

_N = {'два': 2, 'две': 2, 'двух': 2, 'двум': 2, 'двумя': 2, 'три': 3, 'трёх': 3, 'трем': 3, 'трём': 3, 'тремя': 3,
      'четыре': 4, 'четырёх': 4, 'четырем': 4, 'четырьмя': 4, 'пять': 5, 'пяти': 5, 'пятью': 5, 'шесть': 6, 'шести': 6,
      'семь': 7, 'семи': 7, 'восемь': 8, 'восьми': 8, 'девять': 9, 'девяти': 9, 'десять': 10, 'десяти': 10,
      'одиннадцать': 11, 'двенадцать': 12, 'тринадцать': 13, 'четырнадцать': 14, 'пятнадцать': 15,
      'шестнадцать': 16, 'семнадцать': 17, 'восемнадцать': 18, 'девятнадцать': 19, 'двадцать': 20, 'двадцати': 20,
      'тридцать': 30, 'тридцати': 30, 'сорок': 40, 'сорока': 40, 'пятьдесят': 50, 'шестьдесят': 60,
      'семьдесят': 70, 'восемьдесят': 80, 'девяносто': 90, 'сто': 100, 'двести': 200, 'триста': 300,
      'четыреста': 400, 'пятьсот': 500, 'двое': 2, 'двоих': 2, 'трое': 3, 'троих': 3, 'четверо': 4, 'четверых': 4,
      'пятеро': 5, 'пятерых': 5, 'шестеро': 6, 'шестерых': 6, 'семеро': 7, 'семерых': 7, 'оба': 2, 'обе': 2,
      'обоих': 2, 'обеих': 2}
_ORD = re.compile(r'^(перв|втор|трет|четв[её]рт|пят|шест|седьм|восьм|девят|десят|[а-я]*надцат|сороков|пятидесят|'
                  r'шестидесят|семидесят|восьмидесят|девяност|сот|тысячн)[а-я]*$')
_TIME = re.compile(r'^(год|лет|час|утр|вечер|ноч|раз)')
# Слова, при которых разные числа в разных местах обычны: время, расстояние, деньги, меры.
_FREE = ('дня', 'дне', 'день', 'суто', 'неде', 'меся', 'мину', 'секу', 'час', 'вер', 'кило', 'метр', 'рубл', 'копе',
         'пуд', 'литр', 'грам', 'шаг', 'раз', 'лет', 'год', 'стор', 'сотк', 'гект', 'трудо', 'штук', 'кило')
_CONJ = ('а', 'и', 'но', 'или', 'да', 'с', 'со', 'на', 'в', 'по', 'до', 'из', 'за')
_BODY2 = re.compile(r'^(рук[аиуеы]?|руками|руках|ног[аиуеы]?|ногами|ногах|глаз[аы]?|глазами|глазах|уши|ушей|ушами|ладон[иьея]|ладонями|плеч[аи]?)$')


def _w(s):
    return re.findall(r'[А-Яа-яЁё]+(?:-[А-Яа-яЁё]+)?', s)


def numbers(sent):
    """[(значение, слово-число, следующее слово)] без порядковых, годов, «два-три»."""
    w = _w(sent)
    out, i = [], 0
    while i < len(w):
        lw = w[i].lower()
        if '-' in lw:            # «два-три», «три-четыре»: примерно, не считаем
            i += 1; continue
        if lw not in _N:
            i += 1; continue
        val, j = _N[lw], i + 1
        if val >= 20 and j < len(w) and w[j].lower() in _N and _N[w[j].lower()] < 10:
            val += _N[w[j].lower()]; j += 1
        nxt = w[j].lower().replace('ё', 'е') if j < len(w) else ''
        if _ORD.match(nxt) or _TIME.match(nxt):
            i = j; continue
        # Возраст и перечни «Тане пятнадцать, Мише двенадцать»: после числа имя или конец, слово не берём
        if j >= len(w) or not w[j][0].islower() or nxt in _CONJ:
            nxt = ''
        out.append((val, lw, nxt)); i = j
    return out


def sentences(paras):
    out = []
    for p in paras:
        for x in re.split(r'(?<=[.!?…])\s+', p):
            x = x.strip('— ').strip()
            if x:
                out.append(x)
    return out


def report(paras):
    """Возвращает (ошибки, на_проверку): ошибки — список строк для ИСПРАВИТЬ, на_проверку — строки для ПРОВЕРИТЬ."""
    hard, soft, stems = [], [], {}
    for s in sentences(paras):
        n = numbers(s)
        low = s.lower().replace('ё', 'е')
        for v, lw, nxt in n:
            if nxt.startswith(('пальц', 'палец', 'пальч')) and v > 10:
                hard.append(f'«{lw} {nxt}»: у человека десять пальцев')
            if _BODY2.match(nxt) and v > 2:
                soft.insert(0, f'«{lw} {nxt}»: у человека их два (если это не стол или табурет)')
            if nxt and not nxt.startswith(_FREE):
                stems.setdefault(nxt[:5], {}).setdefault(v, f'{lw} {nxt}')
        vals = [v for v, _, x in n if x and not x.startswith(_FREE)]  # без слова после числа (возраст) и дни, вёрсты, рубли в сумму не берём
        if len(vals) >= 2 and len(set(vals)) >= 2:
            line = ' + '.join(str(v) for v in vals) + f' = {sum(vals)}: «{s[:150]}»'
            if (re.search(r'пал(ец|ьц|ьч)', low) and sum(vals) > 10
                    and not any(_BODY2.match(x) for _, _, x in n)):
                hard.append('пальцев в частях больше десяти: ' + line)
            else:
                soft.append('части и целое сходятся? ' + line)
    for st, d in stems.items():
        if len(d) > 1:
            soft.append('одно слово, разные числа (если про одно и то же, свести): ' + ', '.join(d[v] for v in sorted(d)))
    return list(dict.fromkeys(hard)), list(dict.fromkeys(soft))


if __name__ == '__main__':
    if len(sys.argv) < 2:
        print('Укажите файл рассказа'); sys.exit(1)
    t = open(sys.argv[1], encoding='utf-8').read()
    t = re.sub(r'```.*?```', '', t, flags=re.S)
    t = re.sub(r'\*\*\[.*?\]\*\*', '', t)
    ps = [l.strip() for l in t.split('\n') if l.strip() and not l.startswith('Подпись:')][1:]
    h, s = report(ps)
    for x in h: print('ИСПРАВИТЬ Числа (Л20):', x)
    for x in s: print('ПРОВЕРИТЬ Числа (Л20):', x)
    print('ИТОГ чисел:', 'исправить' if h else ('сверить строки выше' if s else 'всё в норме'))
